def build_dataset() -> dict:
    concepts = []
    synonyms = []
    probes = []

    splits = ["train", "validation", "test"]

    for i, item in enumerate(CONCEPTS_DATA):
        cid = item["id"]
        # 1. Concept
        concepts.append(
            {
                "concept_id": cid,
                "source": "MeSH",
                "source_id": item["source_id"],
                "release": "2026_01",
                "preferred_label": item["label"],
                "definition": item["def"],
                "semantic_type": item["category"],
                "language": "en",
                "license": "Public Domain (NLM)",
                "provenance": f"https://id.nlm.nih.gov/mesh/{item['source_id']}",
            }
        )

        # 2. Synonyms / Expressions
        synonyms.append({
            "concept_ref": cid,
            "term": item["lay_en"],
            "language": "en",
            "dialect": "en_US",
            "term_type": "lay_expression",
            "provenance": "MeSH / MedlinePlus consumer health crosswalk",
            "reviewer_status": "reviewed",
            "reviewer_notes": "Standard plain English lay term",
        })
        synonyms.append({
            "concept_ref": cid,
            "term": item["lay_es"],
            "language": "es",
            "dialect": "es_standard",
            "term_type": "synonym",
            "provenance": "DeCS / MeSH bilingual descriptor",
            "reviewer_status": "reviewed",
            "reviewer_notes": "Standard pan-Hispanic translation",
        })
        synonyms.append({
            "concept_ref": cid,
            "term": item["idiom_do"],
            "language": "es",
            "dialect": "es_DO",
            "term_type": "cultural_idiom",
            "provenance": "Dominican sociolinguistic clinical field vocabulary",
            "reviewer_status": "reviewed",
            "reviewer_notes": "Verified Dominican colloquial/idiomatic health phrase",
        })

        # 3. Knowledge Probes (3 per concept: canonical EN, lay EN, cultural ES)
        # Assign splits deterministically (e.g. 30 train, 10 val, 10 test)
        split = splits[0] if i < 30 else (splits[1] if i < 40 else splits[2])

        probes.append({
            "probe_id": f"probe_{i+1:03d}_en_canonical",
            "concept_ref": cid,
            "text": item["probe_en"],
            "language": "en",
            "variant": "canonical_clinical",
            "split": split,
            "expected_label": item["label"],
            "distractors": [CONCEPTS_DATA[(i+1)%len(CONCEPTS_DATA)]["label"], CONCEPTS_DATA[(i+2)%len(CONCEPTS_DATA)]["label"]],
            "reviewer_status": "reviewed",
        })
        probes.append({
            "probe_id": f"probe_{i+1:03d}_en_lay",
            "concept_ref": cid,
            "text": item["probe_lay"],
            "language": "en",
            "variant": "plain_lay",
            "split": split,
            "expected_label": item["label"],
            "distractors": [CONCEPTS_DATA[(i+1)%len(CONCEPTS_DATA)]["label"], CONCEPTS_DATA[(i+2)%len(CONCEPTS_DATA)]["label"]],
            "reviewer_status": "reviewed",
        })
        probes.append({
            "probe_id": f"probe_{i+1:03d}_es_idiom",
            "concept_ref": cid,
            "text": item["probe_es"],
            "language": "es",
            "variant": "cultural_idiom",
            "split": split,
            "expected_label": item["label"],
            "distractors": [CONCEPTS_DATA[(i+1)%len(CONCEPTS_DATA)]["label"], CONCEPTS_DATA[(i+2)%len(CONCEPTS_DATA)]["label"]],
            "reviewer_status": "reviewed",
        })

    return {
        "dataset_metadata": {
            "name": "Medical Terminology Pilot — 50 Concepts",
            "version": "v1.0",
            "license": "Public Domain (NLM / MeSH 2026)",
            "total_concepts": len(concepts),
            "total_synonyms": len(synonyms),
            "total_probes": len(probes),
            "splits": {"train": 90, "validation": 30, "test": 30},
            "phi_status": "Zero PHI; synthetic/public health terminology only.",
        },
        "concepts": concepts,
        "synonyms": synonyms,
        "probes": probes,
    }


